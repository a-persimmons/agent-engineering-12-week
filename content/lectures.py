def attach_lectures(course: list[dict], out: Path) -> None:
    """Enrich chapters and export readable handouts from the same content source."""
    folder = out / 'handouts'
    folder.mkdir(exist_ok=True)
    for week in course:
        lecture = LECTURES[week['id']]
        assert len(lecture['sections']) == len(week['concepts']), week['id']
        week['lecture'] = {key: value for key, value in lecture.items() if key != 'sections'}
        week['lecture']['path'] = f"handouts/week-{week['id']:02d}.md"
        for concept, expansion in zip(week['concepts'], lecture['sections']):
            concept['discussion'] = expansion
        heading = f"第 {week['id']} 周" if week['id'] else '准备课'
        parts = [f"# {heading}讲义 · {week['title']}", '## 学习目标',
                 '\n'.join('- '+item for item in week['goals']),
                 '## 本讲的问题', lecture['question'], *lecture['opening']]
        for concept in week['concepts']:
            parts += ['## '+concept['title'], *concept['body'], concept['discussion']]
            if concept.get('example'):
                parts += ['**案例联系：**'+concept['example']]
            if concept.get('diagram'):
                diagram = concept['diagram']
                parts += [f"![{diagram['alt']}](../{diagram['src']})", diagram['caption'],
                          '\n'.join(f'{i}. {step}' for i, step in enumerate(diagram['steps'], 1))]
        parts += ['## 回到代码', *lecture['reading'], '## 本讲小结', lecture['recap'],
                  '## 迁移练习', lecture['exercise'], '**参考思路：**'+lecture['answer'],
                  '## Python 示例与运行', *week['setup'], '```bash\n'+week['command']+'```']
        for example in week['examples']:
            parts += ['### '+example['file'], example['description'],
                      f"```{example['lang']}\n{example['code']}```"]
        parts += ['## 预期现象', week['expected'], '## 运行边界', week['limit'],
                  '## 动手任务', week['task']['title'], *week['task']['body'],
                  '## 验收标准', '\n'.join('- '+item for item in week['criteria']),
                  '## 参考资料', '\n'.join(f'- [{title}]({url})' for title, url in week['refs']),
                  '配图使用相对链接；离线查看配图时请同时保留 dist/diagrams 目录。配套 Python 文件与依赖请下载本周代码包。']
        (folder / f"week-{week['id']:02d}.md").write_text('\n\n'.join(parts)+'\n', encoding='utf-8')
